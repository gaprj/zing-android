    "system" to "🌐 Automatic (System)",
    "it" to "🇮🇹 Italiano",
    "en" to "🇬🇧 English",
    "es" to "🇪🇸 Español",
    "fr" to "🇫🇷 Français",
    "de" to "🇩🇪 Deutsch",
    "pt" to "🇵🇹 Português"
)

fun stringsFor(code: String): AppStrings {
    val resolved = if (code == "system" || code.isBlank()) {
        Locale.getDefault().language.lowercase(Locale.ROOT)
    } else {
        code.lowercase(Locale.ROOT)
    }
    return when (resolved) {
        "en" -> EnStrings
        "es" -> EsStrings
        "fr" -> FrStrings
        "de" -> DeStrings
        "pt" -> PtStrings
        else -> ItStrings
    }
}

